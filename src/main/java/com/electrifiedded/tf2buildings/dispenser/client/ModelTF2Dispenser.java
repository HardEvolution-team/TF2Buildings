   private void rotateHatch(TileEntityTF2Dispenser te) {
      float step = 0.006457718F;
      if (te.isActive() && te.hatchAngle > -0.6457718F) te.hatchAngle = Math.max(-0.6457718F, te.hatchAngle - step);
      if (!te.isActive() && te.hatchAngle < 0.0F) te.hatchAngle = Math.min(0.0F, te.hatchAngle + step);
      this.hatch1.rotateAngleZ = this.hatch2.rotateAngleZ = this.hatch3.rotateAngleZ = te.hatchAngle;
      this.hatch4.rotateAngleZ = this.hatch5.rotateAngleZ = this.hatch6.rotateAngleZ = -te.hatchAngle;
   }

   private void setRotation(ModelRenderer model, float x, float y, float z) {
      model.rotateAngleX = x;
      model.rotateAngleY = y;
      model.rotateAngleZ = z;
   }
